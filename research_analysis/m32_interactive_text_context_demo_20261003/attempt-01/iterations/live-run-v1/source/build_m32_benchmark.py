def _object(object_id, mention, object_type, tags, *, color=None, state=None, aliases=()):
    item = {
        "object_id": object_id,
        "mention": mention,
        "object_type": object_type,
        "expected_affordance_tags": list(tags),
        "acceptable_aliases": list(aliases),
    }
    if color is not None:
        item["explicit_color"] = color
    if state is not None:
        item["explicit_state"] = state
    return item


def _trajectory(scene_id, label, sequence, acceptable, ambiguities, sensitivity_pair_id):
    all_ids = [item["object_id"] for item in _SCENES_BY_ID[scene_id]["objects"]]
    points = []
    for index in range(len(sequence)):
        history = list(sequence[:index + 1])
        remaining = [object_id for object_id in all_ids if object_id not in set(history)]
        point = {
            "point_id": "{}-{}-r{:02d}".format(scene_id, label, index + 1),
            "selection_round": index + 1,
            "history_object_ids": history,
            "candidate_object_ids": remaining,
            "acceptable_next_targets": list(dict.fromkeys(acceptable[index])),
            "expected_ambiguity": bool(ambiguities[index]),
            "label_note": "independently authored semantic alternatives; not generated by DeepSeek",
        }
        if index == 1:
            point["history_sensitivity_pair_id"] = sensitivity_pair_id
        points.append(point)
    return {
        "trajectory_id": "{}-{}".format(scene_id, label),
        "selection_order": list(sequence),
        "decision_points": points,
    }


