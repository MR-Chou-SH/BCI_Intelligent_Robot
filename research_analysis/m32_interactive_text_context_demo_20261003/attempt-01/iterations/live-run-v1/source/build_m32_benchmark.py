_SCENES_BY_ID = {scene["scene_id"]: scene for scene in _SCENES}


def build_payload() -> dict:
    scenes = []
    for raw in _SCENES:
        all_ids = [item["object_id"] for item in raw["objects"]]
        trajectories = []
        for spec in raw["trajectories"]:
            trajectories.append(_trajectory(
                raw["scene_id"], spec["label"], spec["sequence"], spec["acceptable"], spec["ambiguity"],
                raw["scene_id"] + "-reversed-first-two",
            ))
        scenes.append({
            "scene_id": raw["scene_id"], "family": raw["family"], "scene_type": raw["scene_type"],
            "scene_text": raw["scene_text"], "objects": raw["objects"], "selectable_object_ids": all_ids,
            "trajectories": trajectories,
        })
    repeatability_points = [
        "laundry-room-shirt-first-r02",
        "kitchen-knife-first-r02",
        "study-office-book-first-r03",
        "bedroom-clothing-hanger-first-r02",
        "electronics-desk-phone-first-r02",
        "mixed-ambiguous-phone-first-r02",
        "kitchen-apple-first-r04",
        "electronics-desk-charger-first-r03",
    ]
    return {
        "schema_version": SCHEMA_VERSION,
        "benchmark_id": "m32_interactive_text_context_20261003_attempt01",
        "prevalidation_revision": "v2",
        "prevalidation_revision_reason": "removed acceptable-target labels that referenced already-selected objects before any live model call",
        "frozen_at_utc": datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z"),
        "scene_count": len(scenes),
        "scene_family_count": len({scene["family"] for scene in scenes}),
        "trajectory_count": sum(len(scene["trajectories"]) for scene in scenes),
        "decision_point_count": sum(len(path["decision_points"]) for scene in scenes for path in scene["trajectories"]),
        "repeatability_point_ids": repeatability_points,
        "ground_truth_source": "independently authored scene/object/relation alternatives; never generated from model output",
        "model_input_contract": "runner sends only scene_text to TextSceneParser and parsed scene/history/task state/candidates to M30; expected labels are scorer-only",
        "scenes": scenes,
    }


def _canonical(payload: dict) -> bytes:
    return json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def _demo_cases(payload: dict) -> dict:
    return {
        "schema_version": SCHEMA_VERSION,
        "scenes": [
            {"scene_id": scene["scene_id"], "family": scene["family"], "scene_text": scene["scene_text"],
             "objects": [{key: obj[key] for key in ("object_id", "mention", "object_type", "explicit_color", "explicit_state") if key in obj}
                         for obj in scene["objects"]],
             "suggested_sequences": [path["selection_order"] for path in scene["trajectories"]]}
            for scene in payload["scenes"]
        ],
    }


def main() -> None:
    benchmark_path = ROOT / "text_scene_sequence_benchmark.json"
    lock_path = ROOT / "text_scene_sequence_benchmark_lock.json"
    cases_path = ROOT / "text_scene_demo_cases.json"
    for path in (benchmark_path, lock_path, cases_path):
        if path.exists():
            raise FileExistsError("refusing to overwrite frozen M32 artifact: {}".format(path.name))
    payload = build_payload()
    digest = hashlib.sha256(_canonical(payload)).hexdigest()
    lock = {
        "benchmark_id": payload["benchmark_id"],
        "canonical_sha256": digest,
        "scene_count": payload["scene_count"],
        "trajectory_count": payload["trajectory_count"],
        "decision_point_count": payload["decision_point_count"],
        "locked_at_utc": payload["frozen_at_utc"],
        "ground_truth_authored_before_live_model_calls": True,
    }
    for path, value in ((benchmark_path, payload), (lock_path, lock), (cases_path, _demo_cases(payload))):
        with path.open("x", encoding="utf-8", newline="\n") as stream:
            json.dump(value, stream, ensure_ascii=False, indent=2)
            stream.write("\n")
    print(json.dumps(lock, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
