def _case(case_id, category, selected, relations, *, status="executable", task=None,
          context=(), colors=(), states=(), forbidden=(), note=""):
    return {
        "case_id": case_id,
        "category": category,
        "selected_objects": list(selected),
        "scene_context_objects": list(context),
        "task_context": task,
        "expected_status": status,
        "acceptable_relations": list(relations),
        "explicit_colors": [{"object_index": index, "color": color} for index, color in colors],
        "explicit_states": [{"object_index": index, "state": state} for index, state in states],
        "forbidden_object_mentions": list(forbidden),
        "label_note": note,
    }


