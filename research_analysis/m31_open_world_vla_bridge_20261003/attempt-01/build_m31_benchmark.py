def _canonical_bytes(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def build():
    cases = []
    for _category, rows in GROUPS:
        for index, row in enumerate(rows):
            split = "train" if index < 4 else "dev" if index == 4 else "heldout"
            evaluation = {
                "expected_status": row["expected_status"],
                "acceptable_relations": row["acceptable_relations"],
                "explicit_colors": row["explicit_colors"],
                "explicit_states": row["explicit_states"],
                "forbidden_object_mentions": row["forbidden_object_mentions"],
                "label_note": row["label_note"],
            }
            cases.append({
                "case_id": row["case_id"], "category": row["category"], "split": split,
                "input": {
                    "selected_objects": row["selected_objects"],
                    "scene_context_objects": row["scene_context_objects"],
                    "task_context": row["task_context"],
                },
                "evaluation": evaluation,
            })
    if len(cases) != 84 or len({row["case_id"] for row in cases}) != len(cases):
        raise ValueError("M31 benchmark must contain 84 uniquely identified cases")
    payload = {
        "schema_version": "m31-open-world-bridge-benchmark-v1",
        "benchmark_version": "2026-10-03-v1",
        "ground_truth_source": "independently human-authored relation/status labels; no evaluated-model output used",
        "model_input_fields": ["input.selected_objects", "input.scene_context_objects", "input.task_context"],
        "split_counts": {split: sum(case["split"] == split for case in cases) for split in ("train", "dev", "heldout")},
        "category_counts": {category: len(rows) for category, rows in GROUPS},
        "cases": cases,
    }
    BENCHMARK_PATH.write_bytes(_canonical_bytes(payload) + b"\n")
    digest = hashlib.sha256(_canonical_bytes(payload)).hexdigest()
    lock = {
        "schema_version": "m31-benchmark-lock-v1",
        "benchmark_version": payload["benchmark_version"],
        "canonical_sha256": digest,
        "case_count": len(cases),
        "split_counts": payload["split_counts"],
        "ground_truth_frozen_before_model_calls": True,
    }
    LOCK_PATH.write_bytes(_canonical_bytes(lock) + b"\n")
    manuals = []
    by_id = {case["case_id"]: case for case in cases}
    for case_id in MANUAL_CASE_IDS:
        case = by_id[case_id]
        manuals.append({
            "case_id": case_id,
            "label": "+".join(case["input"]["selected_objects"]),
            "input": case["input"],
            "expected_status": case["evaluation"]["expected_status"],
            "acceptable_relations": case["evaluation"]["acceptable_relations"],
            "actual_result": None,
        })
    MANUAL_PATH.write_bytes(_canonical_bytes({"schema_version": "m31-required-manual-examples-v1", "examples": manuals}) + b"\n")
    print(json.dumps({"case_count": len(cases), "split_counts": payload["split_counts"],
                      "category_counts": payload["category_counts"], "sha256": digest}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    build()
